import type { CountryData, Continent, DrivingSide } from '../types/geo';

function getFlag(iso2: string): string {
  if (!iso2 || iso2.length !== 2) return '🌐';
  const codePoints = [...iso2.toUpperCase()].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65);
  return String.fromCodePoint(...codePoints);
}

function c(
  id: string,
  iso2: string,
  name: string,
  nameZh: string,
  continent: Continent,
  drivingSide: DrivingSide
): CountryData {
  return {
    id,
    iso2,
    iso3: iso2,
    name,
    nameZh,
    flag: getFlag(iso2),
    continent,
    region: '無官方街景覆蓋',
    drivingSide,
    coverage: 'none',
    cameraGens: [],
    plateType: 'white',
    plateDesc: '無街景',
    roadLines: ['white_dashed'],
    roadLinesDesc: '無街景',
    carMeta: ['none'],
    carMetaDesc: '無街景',
    poleDesc: '無資料',
    bollardDesc: '無資料',
    language: '當地語言',
    tld: `.${iso2.toLowerCase()}`,
    keyHints: ['此地區目前尚無 Google 街景官方車載覆蓋']
  };
}

